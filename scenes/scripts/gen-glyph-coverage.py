"""Regenerate src/api/glyph-coverage.ts from the bundled fonts.

Coverage is the intersection of the code points every bundled weight maps, so
a validated string renders with real glyphs at every weight.

Usage (needs fontTools + brotli, not a package dependency):
    python3 -I scripts/gen-glyph-coverage.py
"""

import hashlib
import pathlib

from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONTS = ["Inter-Regular.woff2", "Inter-SemiBold.woff2", "Inter-Bold.woff2"]

sets = [set(TTFont(ROOT / "assets/fonts" / name).getBestCmap()) for name in FONTS]
# Control characters never belong in on-screen text, glyph or not.
covered = sorted(cp for cp in set.intersection(*sets) if cp >= 0x20 and not 0x7F <= cp <= 0x9F)

ranges = []
for cp in covered:
    if ranges and cp == ranges[-1][1] + 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp])

digests = {
    name: hashlib.sha256((ROOT / "assets/fonts" / name).read_bytes()).hexdigest() for name in FONTS
}

lines = [
    "// GENERATED by scripts/gen-glyph-coverage.py from assets/fonts/*.woff2 — do not edit.",
    "// Code points every bundled weight of Inter 4.1 has a glyph for, as",
    "// inclusive [first, last] ranges.",
    f"// {len(covered)} code points in {len(ranges)} ranges.",
    "//",
    "// Generated from these font files; a unit test fails if the files change",
    "// without regenerating this table.",
    *[f"//   {name}  sha256 {digest}" for name, digest in digests.items()],
    "export const FONT_SHA256: Readonly<Record<string, string>> = {",
    *[f'  "{name}": "{digest}",' for name, digest in digests.items()],
    "};",
    "",
    "export const GLYPH_RANGES: readonly (readonly [number, number])[] = [",
]
for a, b in ranges:
    lines.append(f"  [0x{a:04x}, 0x{b:04x}],")
lines.append("];")
(ROOT / "src/api/glyph-coverage.ts").write_text("\n".join(lines) + "\n")
print(f"{len(covered)} code points, {len(ranges)} ranges")
